CREATE OR REPLACE FUNCTION public.export_sql_schema(_requesting_user_id uuid)
RETURNS SETOF text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  item record;
  statement text;
  role_list text;
BEGIN
  IF _requesting_user_id IS NULL OR NOT public.has_role(_requesting_user_id, 'gestor'::public.app_role) THEN
    RAISE EXCEPTION 'Acesso negado. Apenas gestores podem exportar a estrutura do banco de dados.';
  END IF;

  RETURN NEXT '-- RH Santa Bárbara - estrutura do banco de dados';
  RETURN NEXT '-- Gerado em ' || now()::text;
  RETURN NEXT '-- Contém o esquema public. Não inclui dados, usuários de acesso, arquivos ou segredos.';
  RETURN NEXT '';
  RETURN NEXT 'SET client_encoding = ''UTF8'';';
  RETURN NEXT 'SET check_function_bodies = false;';
  RETURN NEXT 'BEGIN;';
  RETURN NEXT 'CREATE SCHEMA IF NOT EXISTS public;';
  RETURN NEXT '';

  RETURN NEXT '-- Tipos enumerados';
  FOR item IN
    SELECT t.typname,
           string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder) AS labels
    FROM pg_catalog.pg_type t
    JOIN pg_catalog.pg_namespace n ON n.oid = t.typnamespace
    JOIN pg_catalog.pg_enum e ON e.enumtypid = t.oid
    WHERE n.nspname = 'public'
    GROUP BY t.typname
    ORDER BY t.typname
  LOOP
    RETURN NEXT format('DO $ddl$ BEGIN CREATE TYPE public.%I AS ENUM (%s); EXCEPTION WHEN duplicate_object THEN NULL; END $ddl$;', item.typname, item.labels);
  END LOOP;
  RETURN NEXT '';

  RETURN NEXT '-- Sequências';
  FOR item IN
    SELECT c.relname AS sequence_name,
           s.seqstart, s.seqincrement, s.seqmin, s.seqmax, s.seqcache, s.seqcycle
    FROM pg_catalog.pg_class c
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
    JOIN pg_catalog.pg_sequence s ON s.seqrelid = c.oid
    WHERE n.nspname = 'public'
    ORDER BY c.relname
  LOOP
    RETURN NEXT format(
      'CREATE SEQUENCE IF NOT EXISTS public.%I AS bigint INCREMENT BY %s MINVALUE %s MAXVALUE %s START WITH %s CACHE %s %s;',
      item.sequence_name, item.seqincrement, item.seqmin, item.seqmax, item.seqstart, item.seqcache,
      CASE WHEN item.seqcycle THEN 'CYCLE' ELSE 'NO CYCLE' END
    );
  END LOOP;
  RETURN NEXT '';

  RETURN NEXT '-- Tabelas';
  FOR item IN
    SELECT c.oid, c.relname,
           string_agg(
             format('%I %s%s%s%s',
               a.attname,
               pg_catalog.format_type(a.atttypid, a.atttypmod),
               CASE
                 WHEN a.attidentity = 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                 WHEN a.attidentity = 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
                 WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED'
                 WHEN ad.adbin IS NOT NULL THEN ' DEFAULT ' || pg_get_expr(ad.adbin, ad.adrelid)
                 ELSE ''
               END,
               CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,
               CASE WHEN coll.collname IS NOT NULL AND coll.collname <> 'default' THEN ' COLLATE ' || quote_ident(coll.collname) ELSE '' END
             ),
             E',\n  ' ORDER BY a.attnum
           ) AS columns_sql
    FROM pg_catalog.pg_class c
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
    JOIN pg_catalog.pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
    LEFT JOIN pg_catalog.pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
    LEFT JOIN pg_catalog.pg_collation coll ON coll.oid = a.attcollation AND a.attcollation <> 0
    WHERE n.nspname = 'public'
      AND c.relkind IN ('r', 'p')
      AND NOT c.relispartition
    GROUP BY c.oid, c.relname
    ORDER BY c.relname
  LOOP
    RETURN NEXT format(E'CREATE TABLE IF NOT EXISTS public.%I (\n  %s\n);', item.relname, item.columns_sql);
  END LOOP;
  RETURN NEXT '';

  RETURN NEXT '-- Propriedade das sequências';
  FOR item IN
    SELECT seq.relname AS sequence_name, tab.relname AS table_name, att.attname AS column_name
    FROM pg_catalog.pg_class seq
    JOIN pg_catalog.pg_namespace ns ON ns.oid = seq.relnamespace AND ns.nspname = 'public'
    JOIN pg_catalog.pg_depend dep ON dep.objid = seq.oid AND dep.deptype IN ('a', 'i')
    JOIN pg_catalog.pg_class tab ON tab.oid = dep.refobjid
    JOIN pg_catalog.pg_attribute att ON att.attrelid = tab.oid AND att.attnum = dep.refobjsubid
    WHERE seq.relkind = 'S'
    ORDER BY seq.relname
  LOOP
    RETURN NEXT format('ALTER SEQUENCE public.%I OWNED BY public.%I.%I;', item.sequence_name, item.table_name, item.column_name);
  END LOOP;
  RETURN NEXT '';

  RETURN NEXT '-- Funções';
  FOR item IN
    SELECT p.oid, pg_get_functiondef(p.oid) AS definition
    FROM pg_catalog.pg_proc p
    JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public'
    ORDER BY p.proname, pg_get_function_identity_arguments(p.oid)
  LOOP
    RETURN NEXT item.definition || ';';
  END LOOP;
  RETURN NEXT '';

  RETURN NEXT '-- Restrições';
  FOR item IN
    SELECT con.conname, c.relname AS table_name, pg_get_constraintdef(con.oid, true) AS definition
    FROM pg_catalog.pg_constraint con
    JOIN pg_catalog.pg_class c ON c.oid = con.conrelid
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
    ORDER BY CASE con.contype WHEN 'p' THEN 1 WHEN 'u' THEN 2 WHEN 'c' THEN 3 WHEN 'f' THEN 4 ELSE 5 END,
             c.relname, con.conname
  LOOP
    RETURN NEXT format('ALTER TABLE ONLY public.%I ADD CONSTRAINT %I %s;', item.table_name, item.conname, item.definition);
  END LOOP;
  RETURN NEXT '';

  RETURN NEXT '-- Índices';
  FOR item IN
    SELECT i.indexrelid, pg_get_indexdef(i.indexrelid) AS definition
    FROM pg_catalog.pg_index i
    JOIN pg_catalog.pg_class t ON t.oid = i.indrelid
    JOIN pg_catalog.pg_namespace n ON n.oid = t.relnamespace
    LEFT JOIN pg_catalog.pg_constraint con ON con.conindid = i.indexrelid
    WHERE n.nspname = 'public' AND con.oid IS NULL
    ORDER BY t.relname, i.indexrelid::regclass::text
  LOOP
    RETURN NEXT item.definition || ';';
  END LOOP;
  RETURN NEXT '';

  RETURN NEXT '-- Segurança por linha e políticas';
  FOR item IN
    SELECT c.relname, c.relrowsecurity, c.relforcerowsecurity
    FROM pg_catalog.pg_class c
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p') AND NOT c.relispartition
    ORDER BY c.relname
  LOOP
    IF item.relrowsecurity THEN
      RETURN NEXT format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', item.relname);
    ELSE
      RETURN NEXT format('ALTER TABLE public.%I DISABLE ROW LEVEL SECURITY;', item.relname);
    END IF;
    IF item.relforcerowsecurity THEN
      RETURN NEXT format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY;', item.relname);
    END IF;
  END LOOP;

  FOR item IN
    SELECT p.polname, c.relname AS table_name, p.polpermissive, p.polcmd,
           p.polroles, pg_get_expr(p.polqual, p.polrelid) AS using_expr,
           pg_get_expr(p.polwithcheck, p.polrelid) AS check_expr
    FROM pg_catalog.pg_policy p
    JOIN pg_catalog.pg_class c ON c.oid = p.polrelid
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
    ORDER BY c.relname, p.polname
  LOOP
    SELECT string_agg(quote_ident(r.rolname), ', ' ORDER BY r.rolname)
      INTO role_list
    FROM pg_catalog.pg_roles r
    WHERE r.oid = ANY(item.polroles);

    statement := format('CREATE POLICY %I ON public.%I AS %s FOR %s TO %s',
      item.polname,
      item.table_name,
      CASE WHEN item.polpermissive THEN 'PERMISSIVE' ELSE 'RESTRICTIVE' END,
      CASE item.polcmd WHEN 'r' THEN 'SELECT' WHEN 'a' THEN 'INSERT' WHEN 'w' THEN 'UPDATE' WHEN 'd' THEN 'DELETE' ELSE 'ALL' END,
      COALESCE(role_list, 'PUBLIC')
    );
    IF item.using_expr IS NOT NULL THEN statement := statement || ' USING (' || item.using_expr || ')'; END IF;
    IF item.check_expr IS NOT NULL THEN statement := statement || ' WITH CHECK (' || item.check_expr || ')'; END IF;
    RETURN NEXT statement || ';';
  END LOOP;
  RETURN NEXT '';

  RETURN NEXT '-- Gatilhos';
  FOR item IN
    SELECT pg_get_triggerdef(t.oid, true) AS definition
    FROM pg_catalog.pg_trigger t
    JOIN pg_catalog.pg_class c ON c.oid = t.tgrelid
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND NOT t.tgisinternal
    ORDER BY c.relname, t.tgname
  LOOP
    RETURN NEXT item.definition || ';';
  END LOOP;
  RETURN NEXT '';

  RETURN NEXT '-- Permissões das tabelas';
  FOR item IN
    SELECT table_name, grantee, string_agg(privilege_type, ', ' ORDER BY privilege_type) AS privileges
    FROM information_schema.role_table_grants
    WHERE table_schema = 'public'
      AND grantee IN ('anon', 'authenticated', 'service_role')
    GROUP BY table_name, grantee
    ORDER BY table_name, grantee
  LOOP
    RETURN NEXT format('GRANT %s ON TABLE public.%I TO %I;', item.privileges, item.table_name, item.grantee);
  END LOOP;
  RETURN NEXT '';

  RETURN NEXT '-- Permissões das sequências';
  FOR item IN
    SELECT object_name AS sequence_name, grantee,
           string_agg(privilege_type, ', ' ORDER BY privilege_type) AS privileges
    FROM information_schema.role_usage_grants
    WHERE object_schema = 'public'
      AND object_type = 'SEQUENCE'
      AND grantee IN ('anon', 'authenticated', 'service_role')
    GROUP BY object_name, grantee
    ORDER BY object_name, grantee
  LOOP
    RETURN NEXT format('GRANT %s ON SEQUENCE public.%I TO %I;', item.privileges, item.sequence_name, item.grantee);
  END LOOP;

  RETURN NEXT '';
  RETURN NEXT 'COMMIT;';
  RETURN NEXT '-- Fim da estrutura do banco de dados';
END;
$$;

REVOKE ALL ON FUNCTION public.export_sql_schema(uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.export_sql_schema(uuid) TO service_role;